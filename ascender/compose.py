"""Render the fixed Compose schema; independent of Docker and filesystem access."""


def quote(value) -> str:
    # Compose interpolation happens even inside YAML quotes.
    return "'" + str(value).replace("$", "$$").replace("'", "''") + "'"


def render(image, code_dir, output_dir, groups, devices, driver_mounts, *, subnet):
    lines = ["# Generated by Ascender; no environment interpolation is required."]
    lines.extend(["services:", "  ascend:", f"    image: {quote(image)}", "    pull_policy: never",
             "    user: '0:0'", "    working_dir: /workspace/code",
             '    command: ["sleep", "infinity"]', "    environment:", "      HOME: /workspace/home",
             "      XDG_CACHE_HOME: /workspace/home/.cache"])
    if groups:
        lines.append("    group_add:")
        lines.extend(f"      - {quote(gid)}" for gid in groups)
    if devices:
        lines.append("    devices:")
        lines.extend(f"      - {quote(f'{device}:{device}')}" for device in devices)
    lines.append("    volumes:")
    mounts = [(code_dir, "/workspace/code", False), (output_dir / "home", "/workspace/home", False),
              (output_dir / "identity/passwd", "/etc/passwd", True),
              (output_dir / "identity/group", "/etc/group", True), *driver_mounts]
    for source, target, readonly in mounts:
        lines.extend(("      - type: bind", f"        source: {quote(source)}", f"        target: {quote(target)}"))
        if readonly:
            lines.append("        read_only: true")
        lines.extend(("        bind:", "          create_host_path: false"))
    lines.extend(("networks:", "  default:", "    driver: bridge", "    ipam:", "      config:",
                  f"        - subnet: {quote(subnet)}"))
    return "\n".join(lines) + "\n"
