"""Initialize installed CAModel libraries and environment; stdlib-only container module."""
from pathlib import Path
import os
import re
import shlex
import shutil


def unique(paths, description, option):
    paths = sorted(set(path.resolve() for path in paths))
    if len(paths) != 1:
        listing = "\n".join(f"  {path}" for path in paths) or "  none"
        raise ValueError(f"Expected one {description}, found {len(paths)}:\n{listing}\nSpecify {option}.")
    return paths[0]


def runtime_library(settings, environment):
    explicit = settings["cann_install_dir"]
    active = environment.get("ASCEND_HOME_PATH") or environment.get("ASCEND_TOOLKIT_HOME")
    roots = [Path(explicit or active)] if explicit or active else [
        Path("/usr/local/Ascend/cann"), Path("/usr/local/Ascend/cann/latest"),
        Path("/usr/local/Ascend/ascend-toolkit/latest")]
    requested = settings["esl_soc_version"] or settings["soc"]
    normalize = lambda value: re.sub(r"^ascend", "", value.lower())
    exact, aliases, locations = [], [], []
    for root in roots:
        directory = root / "x86_64-linux/simulator"
        locations.append(directory)
        for child in directory.glob("*"):
            library = child / "lib/libruntime_camodel.so"
            if library.is_file():
                if child.name.lower() == requested.lower():
                    exact.append(library)
                elif normalize(child.name) == normalize(requested):
                    aliases.append(library)
    matches = exact or aliases
    if not matches:
        searched = "\n".join(f"  {path}/{requested}/lib/libruntime_camodel.so" for path in locations)
        raise ValueError(f"Missing CANN simulator runtime for {requested}. Expected:\n{searched}\n"
                         "Set --cann-install-dir and/or --esl-soc-version to the installed container paths.")
    source = unique(matches, "CANN simulator runtime", "--cann-install-dir / --esl-soc-version")
    if source.stat().st_size == 0:
        raise ValueError(f"Empty CANN simulator runtime: {source}")
    # Preserve the selected directory's model name even if its library is a symlink.
    selected = next(path for path in matches if path.resolve() == source)
    return source, selected.parent.parent.name


def library_directory(home, value):
    if value:
        directory = (home / value).resolve()
        try:
            directory.relative_to(home)
        except ValueError as error:
            raise ValueError("--camodel-lib-dir must be inside CAMODEL_HOME.") from error
        driver = directory / "libnpu_drv_camodel.so"
        if not driver.is_file():
            raise ValueError(f"Missing CAModel driver library: {driver}; check --camodel-lib-dir.")
        candidates = [directory]
    else:
        candidates = [path.parent for path in home.rglob("libnpu_drv_camodel.so") if path.is_file()]
        if not candidates:
            raise ValueError(f"Missing CAModel driver library: {home}/**/libnpu_drv_camodel.so; check the ZIP contents or --camodel-lib-dir.")
    directory = unique(candidates, "CAModel library directory containing libnpu_drv_camodel.so", "--camodel-lib-dir")
    if any(ord(char) < 32 or ord(char) == 127 or char == ":" for char in str(directory)):
        raise ValueError(f"CAModel library directory cannot contain control characters or colons: {directory!s}")
    if (directory / "libnpu_drv_camodel.so").stat().st_size == 0:
        raise ValueError(f"Empty CAModel driver library: {directory / 'libnpu_drv_camodel.so'}")
    return directory


def environment_script(directory, esl_soc_version, esl_hardware_version):
    return f'''# Generated by Ascender; source this file from Bash.
export ASCEND_DEVICE_ID=0
export ESL_HARDWARE_VERSION={shlex.quote(esl_hardware_version)}
export ESL_SOC_VERSION={shlex.quote(esl_soc_version)}
_ascend_camodel_env() {{
    local directory={shlex.quote(str(directory))} entry
    local -a entries=()
    IFS=: read -r -a entries <<< "${{LD_LIBRARY_PATH:-}}"
    LD_LIBRARY_PATH=$directory
    for entry in ${{entries[@]+"${{entries[@]}}"}}; do
        [[ -z "$entry" || "$entry" == "$directory" ]] || LD_LIBRARY_PATH+=":$entry"
    done
    export LD_LIBRARY_PATH
}}
_ascend_camodel_env
unset -f _ascend_camodel_env
'''


def initialize(settings, home, loader=Path("/etc/ascend/camodel-env.sh"), environment=None):
    home = Path(home).resolve()
    source, simulator_model = runtime_library(settings, os.environ if environment is None else environment)
    directory = library_directory(home, settings["camodel_lib_dir"])
    esl_soc_version = settings["esl_soc_version"] or simulator_model
    esl_hardware_version = settings["esl_hardware_version"]
    if not re.fullmatch(r"[A-Za-z0-9_.-]+", esl_soc_version):
        raise ValueError("ESL_SOC_VERSION must be a nonempty value without shell syntax or whitespace.")
    if not re.fullmatch(r"(?:0[xX][0-9a-fA-F]+|[0-9]+)", esl_hardware_version):
        raise ValueError("ESL_HARDWARE_VERSION must be a decimal or hexadecimal number.")
    for name in ("libruntime_camodel.so", "libruntime.so", "libascend_hal.so", "set_env.sh"):
        path = directory / name
        if path.is_dir() and not path.is_symlink():
            raise ValueError(f"CAModel output path is a directory: {path}")
        if path.is_symlink():
            path.unlink()
    target = directory / "libruntime_camodel.so"
    shutil.copyfile(source, target)
    target.chmod(0o644)
    for name, link in (("libruntime.so", "libruntime_camodel.so"), ("libascend_hal.so", "libnpu_drv_camodel.so")):
        path = directory / name
        path.unlink(missing_ok=True)
        path.symlink_to(link)
    script = directory / "set_env.sh"
    script.write_text(environment_script(directory, esl_soc_version, esl_hardware_version))
    script.chmod(0o644)
    loader = Path(loader)
    loader.parent.mkdir(parents=True, exist_ok=True)
    loader.write_text(f"source {shlex.quote(str(script))}\n")
    loader.chmod(0o644)
    print(f"Initialized CAModel: {directory}\nCANN simulator runtime: {source}\nEnvironment: {script}")
    return directory


if __name__ == "__main__":
    import argparse
    import json
    parser = argparse.ArgumentParser(description="Initialize CAModel libraries and generate set_env.sh.")
    parser.add_argument("settings", type=Path)
    parser.add_argument("home", type=Path)
    args = parser.parse_args()
    initialize(json.loads(args.settings.read_text()), args.home)
